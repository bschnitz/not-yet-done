//! German. Rewrites into the canonical (English) vocabulary; every entry is a
//! phrase, not a computation, so the meanings stay the only place dates are
//! worked out. Words are compared umlaut-folded (`naechste` = `nächste`).
//!
//! The one real ambiguity is `morgen`: lowercased, "tomorrow" and "(the)
//! morning" are the same token. A bare `morgen` is tomorrow; the morning only
//! where the phrase says so (`heute morgen`, `am Morgen`, `morgen früh`).

use super::Entry;

/// `ä` → `ae`, `ö` → `oe`, `ü` → `ue`, `ß` → `ss`.
pub(super) fn fold(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            'ä' => out.push_str("ae"),
            'ö' => out.push_str("oe"),
            'ü' => out.push_str("ue"),
            'ß' => out.push_str("ss"),
            c => out.push(c),
        }
    }
    out
}

