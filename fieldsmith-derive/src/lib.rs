fn lit_to_string(lit: &Lit) -> String {
    match lit {
        Lit::Str(s) => s.value(),
        Lit::Bool(b) => b.value.to_string(),
        Lit::Int(i) => i.base10_digits().to_string(),
        Lit::Float(f) => f.base10_digits().to_string(),
        Lit::Char(c) => c.value().to_string(),
        other => quote! { #other }.to_string(),
    }
}

fn opt_str_tokens(value: Option<&str>) -> TokenStream2 {
    match value {
        Some(s) => {
            let lit = LitStr::new(s, Span::call_site());
            quote! { ::core::option::Option::Some(#lit) }
        }
        None => quote! { ::core::option::Option::None },
    }
}

/// Convert an identifier (snake_case field or PascalCase variant) per serde's
/// `rename_all` style.
fn apply_rename_all(ident: &str, style: &str) -> String {
    let words = split_words(ident);
    let lower = || words.iter().map(|w| w.to_lowercase()).collect::<Vec<_>>();
    let upper = || words.iter().map(|w| w.to_uppercase()).collect::<Vec<_>>();
    match style {
        "lowercase" => lower().concat(),
        "UPPERCASE" => upper().concat(),
        "snake_case" => lower().join("_"),
        "SCREAMING_SNAKE_CASE" => upper().join("_"),
        "kebab-case" => lower().join("-"),
        "SCREAMING-KEBAB-CASE" => upper().join("-"),
        "camelCase" => words
            .iter()
            .enumerate()
            .map(|(i, w)| {
                if i == 0 {
                    w.to_lowercase()
                } else {
                    capitalize(w)
                }
            })
            .collect(),
        "PascalCase" => words.iter().map(|w| capitalize(w)).collect(),
        // Unknown style: leave the name as declared.
        _ => ident.to_string(),
    }
}

/// Split an identifier into words on `_`/`-` separators and lower→upper
/// case boundaries (so both `snake_case` and `PascalCase` inputs work).
fn split_words(ident: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut cur = String::new();
    let mut prev_lower = false;
    for ch in ident.chars() {
        if ch == '_' || ch == '-' {
            if !cur.is_empty() {
                words.push(std::mem::take(&mut cur));
            }
            prev_lower = false;
            continue;
        }
        if ch.is_uppercase() && prev_lower && !cur.is_empty() {
            words.push(std::mem::take(&mut cur));
        }
        cur.push(ch);
        prev_lower = ch.is_lowercase() || ch.is_ascii_digit();
    }
    if !cur.is_empty() {
        words.push(cur);
    }
    words
}

fn capitalize(word: &str) -> String {
    let mut chars = word.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + &chars.as_str().to_lowercase(),
        None => String::new(),
    }
}
